static const unsigned char *glyph(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    for (size_t i = 0; i < sizeof FONT / sizeof FONT[0]; i++)
        if (FONT[i].c == c)
            return FONT[i].rows;
    return FONT[sizeof FONT / sizeof FONT[0] - 1].rows; /* space */
}

void draw_clear(struct fb *fb, uint32_t colour)
{
    size_t n = (size_t)fb->width * fb->height;
    for (size_t i = 0; i < n; i++)
        fb->back[i] = colour;
}

void draw_rect(struct fb *fb, int x, int y, int w, int h, uint32_t colour)
{
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
    int x1 = x + w > (int)fb->width ? (int)fb->width : x + w;
    int y1 = y + h > (int)fb->height ? (int)fb->height : y + h;
    for (int yy = y0; yy < y1; yy++)
        for (int xx = x0; xx < x1; xx++)
            fb->back[(size_t)yy * fb->width + xx] = colour;
}

void draw_disc(struct fb *fb, int cx, int cy, int r, uint32_t colour)
{
    for (int yy = -r; yy <= r; yy++)
        for (int xx = -r; xx <= r; xx++)
            if (xx * xx + yy * yy <= r * r) {
                int px = cx + xx, py = cy + yy;
                if (px >= 0 && py >= 0 && px < (int)fb->width && py < (int)fb->height)
                    fb->back[(size_t)py * fb->width + px] = colour;
            }
}

int draw_text_width(int scale, const char *text)
{
    return (int)strlen(text) * 6 * scale;
}

void draw_text(struct fb *fb, int x, int y, int scale, const char *text, uint32_t colour)
{
    for (; *text; text++, x += 6 * scale) {
        const unsigned char *rows = glyph(*text);
        for (int r = 0; r < 7; r++)
            for (int c = 0; c < 5; c++)
                if (rows[r] & (0x10 >> c))
                    draw_rect(fb, x + c * scale, y + r * scale, scale, scale, colour);
    }
}
